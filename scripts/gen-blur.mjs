/**
 * Generates src/features/images/blur.ts: a tiny (16px) WebP data URI per
 * photograph in public/images, used by SiteImage as the blur placeholder
 * while the real image lazy-loads. Run after adding or replacing photos:
 *
 *   npm run images:blur
 */
import { readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import sharp from "sharp";

const dir = join(process.cwd(), "public", "images");
const files = (await readdir(dir)).filter((f) => /\.(jpe?g|png|webp|avif)$/i.test(f)).sort();

const lines = [];
for (const file of files) {
  const buf = await sharp(join(dir, file)).resize(16, 16, { fit: "inside" }).modulate({ saturation: 1.1 }).webp({ quality: 40 }).toBuffer();
  lines.push(`  "/images/${file}": "data:image/webp;base64,${buf.toString("base64")}",`);
}

const out = `// Generated by scripts/gen-blur.mjs. Do not edit by hand.
/** Blur placeholders keyed by image src. */
export const BLUR: Record<string, string> = {
${lines.join("\n")}
};
`;
await writeFile(join(process.cwd(), "src", "features", "images", "blur.ts"), out);
console.log(`blur.ts: ${files.length} placeholders`);
